"""Deterministic RECIPE_CONTEXT for TinySLM (Python standard library only).

The application, NOT the model, resolves recipe_id and passes it to this
function.  The model chooses only SECTION and CHUNK.  No keyword matching,
classifier or SQL is generated by the model.

Example:
    python tools/tinyslm_mvp/recipe_context.py \\
      --db /path/to/recipes_normalized.sqlite \\
      --recipe-id 'recipe_nlg_lite:...' --section INGREDIENTS --chunk 1

The output is TEXT, not JSON. Chunking is lossless but uses characters, not
TinySLM tokenizer tokens. The caller must enforce its *actual* 512-token
input budget, accounting for the entire dialogue, before model inference.
"""
from __future__ import annotations

import argparse
import json
import sqlite3
from dataclasses import dataclass
from pathlib import Path

SECTIONS = frozenset({"DESCRIPTION", "INGREDIENTS", "PREPARATION", "FULL"})
DEFAULT_PAGE_CHARS = 900
MIN_PAGE_CHARS = 128
MAX_PAGE_CHARS = 4000


@dataclass(frozen=True)
class ContextResult:
    status: str
    section: str
    chunk: int
    total_chunks: int
    title: str
    content: str
    warnings: tuple[str, ...]

    def as_text(self) -> str:
        # Status is a record-availability status, NOT a proof of answer.
        lines = ["TOOL RESULT", "NAME: RECIPE_CONTEXT", f"STATUS: {self.status}",
                 f"SECTION: {self.section}"]
        if self.title:
            lines.append(f"RECIPE: {self.title}")
        if self.total_chunks:
            lines.extend((f"CHUNK: {self.chunk}/{self.total_chunks}",
                          f"HAS_MORE: {'YES' if self.chunk < self.total_chunks else 'NO'}"))
        if self.warnings:
            lines.append("SOURCE_WARNINGS: " + ", ".join(self.warnings))
        if self.status == "FOUND":
            lines.extend(("CONTENT:", self.content))
        return "\n".join(lines)


def split_chunks(source: str, max_chars: int) -> list[str]:
    """Partition exact original text without loss, splitting at linebreaks when possible."""
    if not source:
        return []
    chunks: list[str] = []
    pos = 0
    while pos < len(source):
        end = min(pos + max_chars, len(source))
        if end < len(source):
            # Prefer a newline, so list items usually remain intact. If none,
            # use exact char boundary; do not drop any portion of the text.
            newline = source.rfind("\n", pos + max_chars // 2, end)
            if newline >= 0:
                end = newline + 1
        assert end > pos
        chunks.append(source[pos:end])
        pos = end
    assert "".join(chunks) == source
    return chunks


def render_section(connection: sqlite3.Connection, recipe: sqlite3.Row, section: str,
                   warnings: tuple[str, ...]) -> str:
    rid = recipe["recipe_id"]
    if section == "DESCRIPTION":
        return recipe["description"]  # exact value; may be empty
    if section == "INGREDIENTS":
        # The ingredient parser is heuristic. If punctuation didn't roundtrip,
        # prefer the original raw field over a possibly broken segmentation.
        if "ingredient_delimiters_not_roundtrippable" in warnings:
            return recipe["ingredients_raw"]
        rows = connection.execute(
            "SELECT position, raw FROM ingredients WHERE recipe_id = ? ORDER BY position",
            (rid,)).fetchall()
        return "\n".join(f"{row['position']}. {row['raw']}" for row in rows)
    if section == "PREPARATION":
        rows = connection.execute(
            "SELECT position, text FROM preparation_segments WHERE recipe_id = ? ORDER BY position",
            (rid,)).fetchall()
        return "\n".join(f"SEGMENT {row['position']}: {row['text']}" for row in rows)
    if section == "FULL":
        return "\n".join((
            "TITLE: " + recipe["title"],
            "DESCRIPTION:\n" + (render_section(connection, recipe, "DESCRIPTION", warnings) or "NOT SPECIFIED"),
            "INGREDIENTS:\n" + (render_section(connection, recipe, "INGREDIENTS", warnings) or "NOT SPECIFIED"),
            "PREPARATION:\n" + (render_section(connection, recipe, "PREPARATION", warnings) or "NOT SPECIFIED"),
        ))
    raise ValueError(f"Unsupported SECTION: {section}")


def get_recipe_context(db: Path, recipe_id: str, section: str,
                       chunk: int = 1, max_chars: int = DEFAULT_PAGE_CHARS) -> ContextResult:
    """Fetch one complete, losslessly paginated section for one known recipe."""
    if section not in SECTIONS:
        raise ValueError(f"SECTION must be one of {sorted(SECTIONS)}")
    if not isinstance(chunk, int) or chunk < 1:
        raise ValueError("CHUNK must be a positive integer")
    if not isinstance(max_chars, int) or not MIN_PAGE_CHARS <= max_chars <= MAX_PAGE_CHARS:
        raise ValueError(f"max_chars must be in [{MIN_PAGE_CHARS},{MAX_PAGE_CHARS}]")
    if not isinstance(recipe_id, str) or not recipe_id:
        raise ValueError("recipe_id is an application-supplied, non-empty string")
    db = Path(db).resolve()
    if not db.is_file():
        raise FileNotFoundError(db)
    with sqlite3.connect(f"{db.as_uri()}?mode=ro", uri=True) as conn:
        conn.row_factory = sqlite3.Row
        recipe = conn.execute(
            "SELECT recipe_id, title, description, ingredients_raw, warnings_json "
            "FROM recipes WHERE recipe_id = ?", (recipe_id,)).fetchone()
        if recipe is None:
            return ContextResult("NOT_FOUND", section, chunk, 0, "", "", ())
        warnings = tuple(json.loads(recipe["warnings_json"]))
        source = render_section(conn, recipe, section, warnings)
        pages = split_chunks(source, max_chars)
        if not pages:
            return ContextResult("EMPTY", section, chunk, 0, recipe["title"], "", warnings)
        if chunk > len(pages):
            return ContextResult("CHUNK_NOT_FOUND", section, chunk, len(pages), recipe["title"], "", warnings)
        return ContextResult("FOUND", section, chunk, len(pages), recipe["title"], pages[chunk-1], warnings)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", required=True, type=Path)
    parser.add_argument("--recipe-id", required=True)
    parser.add_argument("--section", required=True, choices=sorted(SECTIONS))
    parser.add_argument("--chunk", type=int, default=1)
    parser.add_argument("--max-chars", type=int, default=DEFAULT_PAGE_CHARS)
    args = parser.parse_args()
    print(get_recipe_context(args.db, args.recipe_id, args.section,
                             args.chunk, args.max_chars).as_text())


if __name__ == "__main__":
    main()